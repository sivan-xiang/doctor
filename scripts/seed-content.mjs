function toMarkdown(a) {
  const lines = ['---'];
  lines.push(`title: ${a.title}`);
  lines.push(`slug: ${a.slug}`);
  lines.push(`category: ${a.category}`);
  lines.push(`scenario: ${a.scenario}`);
  lines.push(`summary: ${a.summary}`);
  if (a.priority != null) lines.push(`priority: ${a.priority}`);
  if (a.keywords?.length) lines.push(`keywords: [${a.keywords.join(', ')}]`);
  lines.push('steps:');
  a.steps.forEach((s) => lines.push(`  - ${s}`));
  lines.push('donts:');
  a.donts.forEach((s) => lines.push(`  - ${s}`));
  lines.push(`when_to_seek_help: ${a.when_to_seek_help}`);
  if (a.special_groups) lines.push(`special_groups: ${a.special_groups}`);
  lines.push(`source: ${SOURCE}`);
  lines.push(`reviewer: ${REVIEWER}`);
  lines.push(`reviewed_at: ${REVIEWED_AT}`);
  lines.push(`updated_at: ${UPDATED_AT}`);
  lines.push(`version: "1.0"`);
  lines.push(`status: published`);
  lines.push(`disclaimer: ${DISCLAIMER}`);
  lines.push('---');
  lines.push('');
  lines.push(a.body.trim());
  lines.push('');
  return lines.join('\n');
}

// 文案长度硬约束检查，避免写出不合规内容
const problems = [];
const slugs = new Set();
for (const a of articles) {
  if ([...a.title].length > 20) problems.push(`${a.slug}: title > 20 字`);
  if ([...a.summary].length > 40) problems.push(`${a.slug}: summary > 40 字`);
  if (a.steps.length < 3 || a.steps.length > 6) problems.push(`${a.slug}: steps 数量 ${a.steps.length}`);
  a.steps.forEach((s, i) => {
    if ([...s].length > 50) problems.push(`${a.slug}: steps[${i}] > 50 字`);
  });
  a.donts.forEach((s, i) => {
    if ([...s].length > 30) problems.push(`${a.slug}: donts[${i}] > 30 字 (${s})`);
  });
  if (slugs.has(a.slug)) problems.push(`${a.slug}: slug 重复`);
  slugs.add(a.slug);
}
if (problems.length) {
  console.error('内容长度校验失败：\n' + problems.join('\n'));
  process.exit(1);
}

// 注意：本脚本只覆盖同名文件，不删除 content 目录下的其他内容，避免误删人工新增的 .md
for (const a of articles) {
  const dir = path.join(CONTENT, a.category);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${a.slug}.md`);
  fs.writeFileSync(file, toMarkdown(a), 'utf8');
}

